public class profit_precentage{
    public static void main(String [] args){
        double cp = 129,sp = 191;
        double profit = sp - cp;
        double profit_percentage = (profit/cp) * 100;
        System.out.println("The Cost Price is INR " + cp + " and selling price is INR " + profit_percentage);
        System.out.println("The Profit is INR " + profit + " and the Profit Percentage is " + profit_percentage);
        
         
    }
}